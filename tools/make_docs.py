"""Step `docs`: the ontology documentation, docs/{index,model,vocabulary,crosswalk}.md.

Classes, properties and superclasses come from ontology/qskos.ttl; the prose
from tools/docs_text.py.  A term without prose fails the step.  Publish with
GitHub Pages (Settings > Pages > branch, folder /docs); docs/_config.yml and
docs/_layouts/default.html are the (hand-written) Jekyll shell.
"""
from __future__ import annotations

from rdflib.namespace import RDFS

from . import docs_text as T
from . import ontology_io as oio

BLOB = "https://github.com/leiza-rse/QSKOS/blob/master/"
HEADER = ("<!-- Generated by tools/main.py (step: docs). "
          "Do not edit by hand; edit tools/docs_text.py or ontology/qskos.ttl. -->\n\n")


def _local(iri) -> str:
    return str(iri).split("#")[-1]


def _fm(title: str) -> str:
    return f"---\ntitle: {title}\n---\n\n"


def _chain(path) -> str:
    return " → ".join(f"`{oio.short(p)}`" for p in path)


def _check_docs(onto):
    missing = [_local(t) for t in oio.qskos_classes(onto) + oio.qskos_properties(onto)
               if _local(t) not in T.TERM_DOCS]
    if missing:
        raise SystemExit("  !!  terms without prose in tools/docs_text.py: " + ", ".join(missing))
    unknown = [k for k in T.TERM_DOCS if oio.QSKOS[k] not in set(onto.subjects())]
    if unknown:
        raise SystemExit("  !!  prose for terms that are not in the ontology: " + ", ".join(unknown))


def _img(name, alt):
    return (f"![{alt}](diagrams/{name}.svg)\n\n"
            f"Sources: [{name}.mmd]({BLOB}docs/diagrams/{name}.mmd) · "
            f"[SVG]({BLOB}docs/diagrams/{name}.svg) · [PNG]({BLOB}docs/diagrams/{name}.png)\n\n")


def index_md(onto) -> str:
    n_c, n_p = len(oio.qskos_classes(onto)), len(oio.qskos_properties(onto))
    return (_fm("Overview") + HEADER + "# QSKOS RDF export\n\n"
        "The *LOD Export* tab of the QSKOS plugin writes annotated features as RDF (Turtle). "
        "The model combines four standards:\n\n"
        "- **DCAT 3** for the metadata of an export (`qskos:Catalog`, `qskos:Dataset`, `qskos:Distribution`),\n"
        "- **GeoSPARQL** for features, geometries and layers, readable by SPARQLing Unicorn,\n"
        "- **Web Annotation** for the annotations (`oa:hasTarget`, `oa:hasBody`, `oa:motivatedBy oa:classifying`),\n"
        "- **CIDOC CRM** (with CRMgeo) as the semantic superstructure of every class.\n\n"
        "The exported data uses only `qskos:` classes. The crosswalk to the four standards is stated "
        f"once, in the application ontology (`ontology/qskos.ttl`: {n_c} classes, {n_p} properties) as `rdfs:subClassOf`.\n\n"
        + _img("model-simple", "QSKOS model") +
        "## Pages\n\n"
        "| Page | Content |\n|---|---|\n"
        "| [Model](model.html) | The three diagrams: data view, CIDOC CRM view, class hierarchy |\n"
        "| [Vocabulary](vocabulary.html) | Every class and property: definition, superclasses, what the plugin writes |\n"
        "| [Crosswalk](crosswalk.html) | QSKOS to DCAT and to CIDOC CRM (and GeoSPARQL, Web Annotation, SKOS) |\n"
        "| [Report](report.html) | Counts for the ontology and the example export |\n\n"
        "## Files\n\n"
        "| File | Purpose |\n|---|---|\n"
        f"| [`ontology/qskos.ttl`]({BLOB}ontology/qskos.ttl) | Application ontology with the crosswalk |\n"
        f"| [`ontology/shapes.ttl`]({BLOB}ontology/shapes.ttl) | SHACL shapes for validating an export |\n"
        f"| [`ontology/queries.rq`]({BLOB}ontology/queries.rq) | Unicorn query, CRM bridge rules (CONSTRUCT), DCAT view, consistency check |\n"
        f"| [`ontology/example.ttl`]({BLOB}ontology/example.ttl) | A synthetic export (generated) |\n\n"
        "## Rebuild\n\n```\npython tools/main.py\n```\n\n"
        "Writes the example, the diagrams (SVG, PNG), this documentation and the report. "
        "See `python tools/main.py --list`.\n")


def model_md(onto) -> str:
    return (_fm("Model") + HEADER + "# Model\n\n"
        "## Data view\n\nWhat an export contains. Yellow: DCAT metadata layer; brown: QSKOS classes; "
        "green: the physical object; violet: vocabulary concepts.\n\n" + _img("model-simple", "QSKOS data model") +
        "One `qskos:Annotation` is written per feature and annotation field. A cell with several selected "
        "concepts gives one annotation with several `oa:hasBody` values. The field concept is stored per annotation "
        "(`qskos:attribute`), because `skos:broaderTransitive` cannot tell in which field a value was recorded.\n\n"
        "## CIDOC CRM view\n\nThe same model with the CRM class of every node. Dotted edges have no CRM property.\n\n"
        + _img("model-cidoc", "QSKOS model, CIDOC CRM view") +
        "## Class hierarchy\n\nGenerated from `ontology/qskos.ttl`: each QSKOS class with its direct superclasses.\n\n"
        + _img("hierarchy", "QSKOS class hierarchy"))


def vocabulary_md(onto) -> str:
    out = [_fm("Vocabulary"), HEADER, "# Vocabulary\n\nNamespace `", str(oio.QSKOS),
           "` (placeholder, to be replaced by a persistent IRI before release).\n\n## Classes\n\n"]
    for c in oio.qskos_classes(onto):
        n = _local(c)
        sups = ", ".join(f"`{oio.short(s)}`" for s in oio.direct_superclasses(onto, c))
        out.append(f"### qskos:{n}\n\n{oio.comment(onto, c)}\n\n- **Superclasses:** {sups}\n"
                   f"- **In an export:** {T.TERM_DOCS[n]}\n\n")
    out.append("## Properties\n\n")
    for p in oio.qskos_properties(onto):
        n = _local(p)
        dom = ", ".join(f"`{oio.short(o)}`" for o in onto.objects(p, RDFS.domain))
        rng = ", ".join(f"`{oio.short(o)}`" for o in onto.objects(p, RDFS.range))
        sp = ", ".join(f"`{oio.short(o)}`" for o in onto.objects(p, RDFS.subPropertyOf))
        out.append(f"### qskos:{n}\n\n{oio.comment(onto, p)}\n\n- **Domain:** {dom or '–'}\n- **Range:** {rng or '–'}\n"
                   + (f"- **Sub-property of:** {sp}\n" if sp else "") + f"- **In an export:** {T.TERM_DOCS[n]}\n\n")
    out.append("## Reused terms\n\nNo metadata property is reinvented: `dct:title`, `dct:description`, `dct:creator`, "
               "`dct:license`, `dct:issued`, `dct:hasPart`, `dct:requires`, `dct:subject`, `dct:conformsTo`, "
               "`dcat:dataset`, `dcat:distribution`, `dcat:mediaType`, `dcat:version`, `geo:hasGeometry`, `geo:asWKT`, "
               "`rdfs:member`, `oa:hasTarget`, `oa:hasBody`, `oa:hasSource`, `oa:hasSelector`, `oa:motivatedBy`, "
               "`as:generator`, `crm:P157_is_at_rest_relative_to`.\n\n## Prefixes\n\n| Prefix | Namespace |\n|---|---|\n")
    for ns, p in sorted(oio.PREFIXES.items(), key=lambda kv: kv[1]):
        out.append(f"| `{p}` | `{ns}` |\n")
    return "".join(out)


def _rows(full, onto, ns_filter):
    rows = []
    for c in oio.qskos_classes(onto):
        for s in oio.direct_superclasses(onto, c):
            if ns_filter(str(s)):
                rows.append((c, s))
    return rows


def crosswalk_md(onto) -> str:
    full = oio.with_parent_stub(onto)
    out = [_fm("Crosswalk"), HEADER, "# Crosswalk\n\nEvery QSKOS class has a superclass in each standard that "
           "applies to it. The links are `rdfs:subClassOf` statements in `ontology/qskos.ttl`; the exported data "
           "does not repeat them.\n\n## To DCAT 3\n\n| QSKOS class | DCAT class | Path to the root |\n|---|---|---|\n"]
    for c, s in _rows(full, onto, lambda x: x.startswith(oio.DCAT)):
        path = next(p for p in oio.subclass_paths(full, c) if p[1] == s)
        out.append(f"| `{oio.short(c)}` | `{oio.short(s)}` | {_chain(path)} |\n")
    out.append("\nProperties: `dcat:dataset` (Catalog to Dataset), `dcat:distribution` (Dataset to Distribution), "
               "`dcat:mediaType`, `dcat:version`, and from Dublin Core terms `dct:title`, `dct:description`, `dct:creator`, "
               "`dct:license`, `dct:issued`, `dct:hasPart` (layers), `dct:requires` (vocabulary schemes), `dct:subject` "
               "(mapped objects), `dct:conformsTo` (this ontology).\n\n"
               "## To CIDOC CRM\n\n| QSKOS class | CRM class | Path to E1 CRM Entity (all paths) |\n|---|---|---|\n")
    for c, s in _rows(full, onto, lambda x: x.startswith((oio.CRM, oio.CRMGEO))):
        paths = [p for p in oio.subclass_paths(full, c) if p[1] == s]
        out.append(f"| `{oio.short(c)}` | `{oio.short(s)}` | " + "<br>".join(_chain(p) for p in paths) + " |\n")
    out.append("\n### Properties\n\n| QSKOS-side property | CRM property | How | Note |\n|---|---|---|---|\n")
    for a, b, how, note in T.PROPERTY_BRIDGES:
        out.append(f"| `{a}` | `{b}` | {how} | {note} |\n")
    out.append("\n## To GeoSPARQL, Web Annotation and SKOS\n\n| QSKOS class | Superclass | Standard |\n|---|---|---|\n")
    std = {"http://www.opengis.net/ont/geosparql#": "GeoSPARQL", "http://www.w3.org/ns/oa#": "Web Annotation",
           "http://www.w3.org/2004/02/skos/core#": "SKOS"}
    for c, s in _rows(full, onto, lambda x: x.startswith(tuple(std))):
        out.append(f"| `{oio.short(c)}` | `{oio.short(s)}` | {next(v for k, v in std.items() if str(s).startswith(k))} |\n")
    out.append("\n## Decisions and pitfalls\n\n")
    for head, text in T.CROSSWALK_NOTES:
        out.append(f"### {head}\n\n{text}\n\n")
    return "".join(out)


def run(**_):
    onto = oio.ontology()
    _check_docs(onto)
    oio.DOCS.mkdir(exist_ok=True)
    for name, fn in (("index", index_md), ("model", model_md),
                     ("vocabulary", vocabulary_md), ("crosswalk", crosswalk_md)):
        (oio.DOCS / f"{name}.md").write_text(fn(onto), encoding="utf-8", newline="\n")
        print(f"  docs/{name}.md")
